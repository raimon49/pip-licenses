# only one demo right now (TODO: automate rest of demo workflow)
RECORDING=$(dirname "${0}")/../examples/00-demo/00-example-demo.tty ;
DEMO_CMD_PATH=$(dirname "${0}")/../examples/00-demo/00-example-demo.sh ;
# see-also Makefile
REPO_NAME=$(basename `git rev-parse --show-toplevel`)
VENV_NAME="venv/${REPO_NAME:-demo}"

cleanup() {
    printf "\nDeactivating demo environment...\n" ;
    deactivate 2>/dev/null || : ;
    printf "\nCelaning-up demo environment...\n" ;
    make local-uninstall ;
    make un-setup >/dev/null ;
}
trap cleanup EXIT

# trivial checks
